'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createServiceHealth}=require('../lib/service-health');
const {artifactPaths,checkArtifacts}=require('./check-windows-artifacts');
const {localeCoverage}=require('../lib/diagnostics');
const root=path.resolve(__dirname,'..'),temp=fs.mkdtempSync(path.join(os.tmpdir(),'alm36-release-'));
let checks=0;
function check(name,fn){fn();checks++;console.log('OK Beta36:',name);}
(async()=>{
 let now=100000,calls=0,status=406,headers;
 const h=createServiceHealth({now:()=>now,fetchText:async(url,options)=>{calls++;headers=options.headers;assert.equal(options.method,'GET');assert(url.startsWith('https://kitsu.app/api/edge/anime?'));return {response:{ok:status===200,status,headers:new Headers(status===429?{'retry-after':'120'}:{})},text:JSON.stringify({data:[{id:'1',type:'anime'}]})};}});
 assert.equal((await h.test('kitsu')).state,'unavailable');
 check('Kitsu diagnostic sends the JSON:API Accept header',()=>assert.equal(headers.Accept,'application/vnd.api+json'));
 status=200;await h.test('kitsu',{force:true});
 check('explicit retries respect the short cooldown',()=>assert.equal(calls,1));
 now+=5001;assert.equal((await h.test('kitsu',{force:true})).state,'available');
 check('an old error can be rechecked without waiting one minute',()=>assert.equal(calls,2));
 status=429;now+=5001;assert.equal((await h.test('kitsu',{force:true})).state,'limited');
 now+=61000;const limited=await h.test('kitsu',{force:true});
 check('Retry-After longer than the ordinary cache is respected',()=>{assert(limited.cached);assert.equal(calls,3);});
 status=200;now+=60000;assert.equal((await h.test('kitsu',{force:true})).state,'available');
 check('testing resumes after Retry-After',()=>assert.equal(calls,4));
 const optional=await h.test('betaseries',{force:true});
 check('optional BetaSeries without a key makes no request',()=>{assert.equal(optional.state,'unconfigured');assert.equal(calls,4);});
 const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
 fs.mkdirSync(path.join(temp,'dist'));fs.writeFileSync(path.join(temp,'package.json'),JSON.stringify(pkg));
 const paths=artifactPaths(temp,pkg);
 check('only the Windows installer is published',()=>{assert.deepEqual(Object.keys(paths),['nsis']);assert(!pkg.build.portable);});
 check('publication fails when the installer is missing',()=>assert.throws(()=>checkArtifacts(temp,undefined,{writeReport:false}),/ENOENT/));
 const fakePe=tag=>{const b=Buffer.alloc(2048,tag);b.write('MZ');b.writeUInt32LE(128,60);b.write('PE\0\0',128);return b;};
 fs.writeFileSync(paths.nsis,fakePe(2));
 check('installer hash and signature are reported',()=>{const report=checkArtifacts(temp,undefined,{checkSignatures:()=>[{status:'NotSigned'}]});assert.equal(report.artifacts.length,1);assert.equal(report.artifacts[0].target,'nsis');assert.equal(report.artifacts[0].sha256.length,64);});
 fs.writeFileSync(paths.nsis,Buffer.from('truncated'));
 check('truncated installer stops publication',()=>assert.throws(()=>checkArtifacts(temp,undefined,{checkSignatures:()=>[],writeReport:false}),/incomplet/));
 pkg.build.nsis.artifactName='../unsafe.exe';
 check('unsafe installer filename is rejected',()=>assert.throws(()=>artifactPaths(temp,pkg),/invalide/));
 check('all seven locale catalogs contain the reference keys',()=>{const c=localeCoverage(root);assert.equal(Object.keys(c).length,7);for(const v of Object.values(c)){assert(v.total>=1088);assert.equal(v.missing.length,0);}});
 console.log(checks+' Beta36 runtime checks passed. PE fixtures are synthetic; this is not a Windows execution test.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>fs.rmSync(temp,{recursive:true,force:true}));
