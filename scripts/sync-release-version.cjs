'use strict';
// The single source of truth for ALM product version, public qualifier and distribution channel.
// Run without args when intentionally preparing a *new* candidate, followed by rebuilding
// the source manifests and the full tests. --check never mutates files.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),src=JSON.parse(fs.readFileSync(path.join(root,'release-version.json'),'utf8'));
assert.match(src.technicalVersion,/^\d+\.\d+\.\d+$/);
assert.equal(src.qualifier,'Bêta stable');
assert.equal(src.distributionChannel,'beta');
assert.equal(src.githubPrerelease,true);
assert.equal(src.publicName,`${src.product} V${src.technicalVersion} ${src.qualifier}`);
const check=process.argv.includes('--check');let changes=0;
function put(name,expected){const file=path.join(root,name),present=fs.existsSync(file)?fs.readFileSync(file,'utf8'):null;if(present===expected)return;
 if(check)throw Error(`Version désynchronisée : ${name}`);
 fs.writeFileSync(file,expected,'utf8');changes++;
}
const pack=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
pack.version=src.technicalVersion;
pack.description=src.publicName+' — bibliothèque anime locale, import protégé, recommandations multi-source, actualités et dictionnaire intégré';
pack.build.nsis.artifactName=src.installerName.replace('-x64.exe','-${arch}.${ext}');
put('package.json',JSON.stringify(pack,null,2)+'\n');
const lock=JSON.parse(fs.readFileSync(path.join(root,'package-lock.json'),'utf8'));
lock.version=src.technicalVersion;lock.packages[''].version=src.technicalVersion;
put('package-lock.json',JSON.stringify(lock,null,2)+'\n');
const client='// Generated from release-version.json by scripts/sync-release-version.cjs.\n'+
  "(()=>{'use strict';window.ALM_RELEASE=Object.freeze("+JSON.stringify(src)+');})();\n';
put('public/release-version.js',client);
put('community/site/release-version.js',client);
put('supabase/functions/alm-public/release.ts',
  '// Generated by scripts/build-community-site.cjs.\nexport const RELEASE_VERSION = '+JSON.stringify(src.technicalVersion)+';\n');
if(check)console.log('OK : version unique '+src.technicalVersion+', canal '+src.distributionChannel+', libellé '+src.publicName);
else console.log(`Version synchronisée : ${src.publicName} (${changes} fichiers modifiés). Regénérer les manifestes SHA-256 et réexécuter les tests.`);
