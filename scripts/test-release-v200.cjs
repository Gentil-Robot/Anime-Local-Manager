'use strict';
// V2.0.0 Bêta stable: product metadata, older beta upgrades, no accidental promotion.
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const release=JSON.parse(read('release-version.json'));
const pkg=JSON.parse(read('package.json')),lock=JSON.parse(read('package-lock.json'));
const {artifactPaths}=require('./check-windows-artifacts');
const V=require('../lib/version-check');
const {chooseAsset}=require('../lib/integrated-updater');
assert.equal(release.technicalVersion,'2.1.0');
assert.equal(release.publicName,'Anime Local Manager V2.1.0 Bêta stable');
assert.equal(release.distributionChannel,'beta');
assert.equal(release.githubPrerelease,true);
assert.equal(pkg.version,release.technicalVersion);
assert.equal(lock.version,pkg.version);
assert.equal(lock.packages[''].version,pkg.version);
assert.equal(pkg.build.appId,'fr.gentilrobot.animelocalmanager');
assert.equal(pkg.build.productName,'Anime Local Manager');
assert.equal(pkg.build.win.target[0],'nsis');
assert.equal(pkg.build.nsis.artifactName,'Anime-Local-Manager-2.1.0-Setup-${arch}.${ext}');
assert.equal(path.basename(artifactPaths(root,pkg).nsis),release.installerName);
assert.equal(release.archiveName,'Anime-Local-Manager-2.1.0-COMPLET.zip');
assert.equal(read('public/design-core.js'),read('community/site/design-core.js'));
const windowsVM={window:{}};
vm.runInNewContext(read('public/release-version.js'),windowsVM);
assert.equal(windowsVM.window.ALM_RELEASE.publicName,release.publicName);
assert.equal(windowsVM.window.ALM_RELEASE.distributionChannel,'beta');
assert.equal(read('public/release-version.js'),read('community/site/release-version.js'));
assert.match(read('public/index.html'),/V2\.1\.0 Bêta stable/);
assert(!read('public/index.html').includes('2.0.0-beta.82'));
assert.match(read('main.js'),/release-version.json/);
assert.match(read('supabase/functions/alm-public/release.ts'),/RELEASE_VERSION = "2\.1\.0"/);
assert.match(read('server.js'),/const BACKUP_VERSION = "2\.0\.0-beta\.82";/,'Old backup format must not be rewritten');
assert.match(read('server.js'),/version:PRODUCT_RELEASE.technicalVersion/);
assert.equal(V.compare('2.0.0','2.0.0-beta.82'),1,'2.0.0 must upgrade from the last Beta82');
assert.equal(V.compare('2.0.0-beta.83','2.0.0'),-1,'A later beta.83 is NOT a valid update from 2.0.0');
assert.equal(V.compare('2.0.1-beta.1','2.0.0'),1,'Next prerelease needs a higher patch base');
const target='v2.1.0',sourceUrl='https://github.com/'+V.REPOSITORY+'/releases/tag/'+target;
const released={tag_name:target,html_url:sourceUrl,prerelease:true,draft:false};
assert.equal(V.selectRelease([{...released,prerelease:false}],'2.0.0-beta.82',true),null,'The current beta must never silently ship as a stable GitHub release');
assert.equal(V.selectRelease([released],'2.0.0-beta.82',true).tag_name,target,'Beta opt-ins can detect the new version');
assert.equal(V.selectRelease([released],'2.0.0-beta.82',false),null,'Stable users must not receive beta prereleases');
const url='https://github.com/'+V.REPOSITORY+'/releases/download/'+target+'/'+release.installerName;
const digest='sha256:'+'e'.repeat(64),asset={name:release.installerName,state:'uploaded',digest,size:1048576,browser_download_url:url};
assert.throws(()=>chooseAsset({available:true,latest:target,prerelease:false,assets:[asset]},{current:'2.0.0-beta.82',platform:'win32',arch:'x64',portable:false}),/ALM_UPDATE_CHANNEL/);
assert.equal(chooseAsset({available:true,latest:target,prerelease:true,assets:[asset]},{current:'2.0.0-beta.82',platform:'win32',arch:'x64',portable:false}).name,release.installerName);
assert.throws(()=>chooseAsset({available:true,latest:target,prerelease:true,assets:[]},{current:'2.0.0-beta.82',platform:'win32',arch:'x64',portable:false}),/ALM_UPDATE_ASSET_MISSING/);
assert.throws(()=>chooseAsset({available:true,latest:target,prerelease:true,assets:[asset]},{current:'2.1.0',platform:'win32',arch:'x64',portable:false}),/ALM_UPDATE_NOT_NEWER/);
assert.match(read('lib/maintenance.js'),/DEFAULTS=\{enabled:false,[^\n]+channel:'beta'/);
const site=JSON.parse(read('community/site/release-manifest.json'));
assert.equal(site.version,pkg.version);
const comp=JSON.parse(read('compliance/release-gates.json'));assert.equal(comp.version,pkg.version);
for(const file of fs.readdirSync(path.join(root,'community/site')).filter(f=>f.endsWith('.html'))){
 assert.match(read('community/site/'+file),/release-version.js/);
}
require('node:child_process').execFileSync(process.execPath,[path.join(root,'scripts/sync-release-version.cjs'),'--check'],{cwd:root,stdio:'pipe'});
require('node:child_process').execFileSync(process.execPath,[path.join(root,'scripts/refresh-release-manifests.cjs'),'--check'],{cwd:root,stdio:'pipe'});
assert.equal(read('public/community-ui-extra.js'),read('community/site/community-ui-extra.js'));
assert(!read('public/community-ui-extra.js').includes('ALM Beta75'));
assert(read('public/community-ui-extra.js').includes('ALM_RELEASE?.publicName'));
require('node:child_process').execFileSync(process.execPath,[path.join(root,'scripts/test-release-console.cjs')],{cwd:root,stdio:'pipe'});
console.log('OK 2.1.0 Bêta stable: version, installateur, canal GitHub, ancien format sauvegarde, client et site.');
